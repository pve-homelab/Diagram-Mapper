/**
 * Licence gate. Usage: node scripts/check-licences.ts [--attribution <file>]
 *
 * Source of truth: `pnpm licenses list --json --prod`. Client/server classification comes from
 * the bundler's client module list written by apps/web/next.config.ts during `next build`,
 * never from package.json position. Run `pnpm build` first; the gate fails without it.
 */
import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  type Dependency,
  type Exception,
  evaluate,
  PASSING,
  type Policy,
  validateExceptions,
} from "./lib/licences.ts";

const root = join(import.meta.dirname, "..");
const CLIENT_MANIFEST = join(root, "apps/web/.next/diagram-mapper-client-packages.json");
const ASSET_MANIFEST = join(root, "assets/ASSET-LICENCES.json");

interface PnpmEntry {
  name: string;
  versions: string[];
  paths: string[];
  license: string;
}

const policy = JSON.parse(readFileSync(join(root, "licence-policy.json"), "utf8")) as Policy;
const exceptionsFile = JSON.parse(readFileSync(join(root, "licence-exceptions.json"), "utf8")) as {
  exceptions: Exception[];
};
const today = new Date().toISOString().slice(0, 10);
const errors = validateExceptions(policy, exceptionsFile.exceptions, today);

if (!existsSync(CLIENT_MANIFEST)) {
  console.error(`Missing ${CLIENT_MANIFEST}. Run \`pnpm build\` before the licence gate.`);
  process.exit(1);
}
const clientPackages = new Set(JSON.parse(readFileSync(CLIENT_MANIFEST, "utf8")) as string[]);

const listing = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--json", "--prod"], { cwd: root, encoding: "utf8" }),
) as Record<string, PnpmEntry[]>;

const deps: (Dependency & { path: string })[] = [];
for (const [licence, entries] of Object.entries(listing)) {
  for (const e of entries) {
    e.versions.forEach((version, i) => {
      deps.push({
        name: e.name,
        version,
        license: e.license ?? licence,
        path: e.paths[i] ?? e.paths[0] ?? "",
      });
    });
  }
}
deps.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const results = evaluate(policy, exceptionsFile.exceptions, deps, clientPackages);

if (existsSync(ASSET_MANIFEST)) {
  const assets = JSON.parse(readFileSync(ASSET_MANIFEST, "utf8")) as {
    assets?: { file?: string; spdx?: string; sourceUrl?: string }[];
  };
  for (const a of assets.assets ?? []) {
    if (!a.spdx || !a.sourceUrl) errors.push(`asset ${a.file ?? "?"}: needs spdx and sourceUrl`);
  }
}

const failures = results.filter((r) => !PASSING.has(r.verdict));
const rows = results.map(
  (r) =>
    `| ${r.dep.name} | ${r.dep.version} | ${r.dep.license ?? "(none)"} | ${r.surface} | ${PASSING.has(r.verdict) ? "pass" : "**FAIL**"} | ${r.detail} |`,
);
const table = [
  "## Licence gate",
  "",
  `${results.length} production packages, ${clientPackages.size} in the client bundle, ${failures.length} failing, ${errors.length} policy-file errors.`,
  "",
  "| Package | Version | Licence | Surface | Result | Detail |",
  "|---|---|---|---|---|---|",
  ...rows,
  "",
  ...errors.map((e) => `- **ERROR** ${e}`),
].join("\n");

console.log(table);
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${table}\n`);

const attrIndex = process.argv.indexOf("--attribution");
const attrTarget = attrIndex > 0 ? process.argv[attrIndex + 1] : undefined;
if (attrTarget) {
  const sections = deps.map((d) => {
    // Licence text plus any NOTICE file: Apache-2.0 section 4 requires carrying NOTICE forward.
    const files = d.path
      ? readdirSync(d.path).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f))
      : [];
    const text =
      files.map((f) => readFileSync(join(d.path, f), "utf8").trim()).join("\n\n") ||
      "(no licence file shipped in the package)";
    return `## ${d.name}@${d.version} — ${d.license}\n\n\`\`\`\n${text}\n\`\`\`\n`;
  });
  writeFileSync(
    attrTarget,
    `# Third-party licences\n\nGenerated by scripts/check-licences.ts. Do not edit.\n\n${sections.join("\n")}`,
  );
}

if (failures.length > 0 || errors.length > 0) process.exit(1);
